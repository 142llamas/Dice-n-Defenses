/**
 * Ability definitions — data, not code (Source of Truth "data-driven content").
 *
 * Phase 4 gives each hero ONE distinct ability. Abilities are kept small and
 * readable on purpose: the phase boundary defers the full fifth-edition action
 * economy, concentration, large spell lists, and reactions. Each ability spends
 * the hero's single ACTION for the turn, just like a basic attack.
 *
 * All content here is ORIGINAL to this project — names, effects, and values are
 * invented, not copied or adapted from any published source. See CONTENT_SOURCES.
 *
 * Ability kinds:
 *   - "single"      : choose one enemy within `rangeTiles`; deal `damage`.
 *   - "aoeAdjacent" : hit EVERY enemy within `rangeTiles` of the hero at once
 *                     (no aiming needed); each takes `damage`.
 *   - "aoeAtRange"  : (Phase 16, D-106) choose any tile within `rangeTiles`;
 *                     hit EVERY enemy within `radiusTiles` of THAT tile —
 *                     the stand-in for every SRD spell that bursts at a
 *                     distance (Fireball, etc.) rather than only adjacent to
 *                     the caster. Reuses `CombatSystem.attackArea` centered
 *                     on the chosen tile instead of the hero.
 *
 * Phase 7 ("spell-like abilities"): an ability may carry `appliesStatus`, a
 * status effect (see data/statusEffects.ts) applied to every enemy it hits, in
 * addition to its damage. This is what makes Bram's slam and Mira's bolt read
 * as spell-like tricks rather than a bigger flat hit — the effect lingers.
 */

export type AbilityKind = "single" | "aoeAdjacent" | "aoeAtRange";

export interface AbilityDefinition {
  id: string;
  name: string;
  description: string;
  kind: AbilityKind;
  /** Reach in tiles (Manhattan distance). For aoeAdjacent this is the radius. */
  rangeTiles: number;
  /** Damage dealt to each affected enemy on a hit. */
  damage: number;
  /**
   * When true, this ability always hits for full damage with no attack roll
   * (Phase 13.1, D-086 — renamed from `ignoreDefense`; an armor-piercing
   * shot that genuinely always lands). Mutually exclusive with
   * `savingThrow` below — a save-targeting spell rolls a save, not an
   * attack roll, so it's never also `autoHit`.
   */
  autoHit?: boolean;
  /**
   * Phase 13.5 (D-090): when present, this ability targets a SAVING THROW
   * instead of an attack roll — the target rolls `ability` vs. the caster's
   * `Hero.spellSaveDC`; `damage` applies in full on a failed save, not at
   * all on a success. The SRD's real mechanic for e.g. Sacred Flame, which
   * this project auto-hit as a stand-in until this sub-phase built a real
   * saving-throw system to resolve it against.
   */
  savingThrow?: { ability: AbilityScoreId };
  /** Phase 7: a status effect applied to every enemy this ability hits. */
  appliesStatus?: { statusId: StatusEffectId; durationTurns: number };
  /**
   * Phase 13.7 (D-092): set only for a leveled spell — which spell-slot
   * level casting it consumes (1 = a 1st-level slot). Absent for a cantrip
   * or a mundane ability, both of which cost no slot.
   */
  spellSlotLevel?: number;
  /**
   * Phase 13.7 (D-092): true for a spell that targets a living ALLY (a
   * `Hero`, including the caster) instead of an enemy — e.g. Cure Wounds.
   * Mutually exclusive with `autoHit`/`savingThrow`, which only make sense
   * against an enemy. `damage` is unused for such an ability; `healAmount`
   * is what it applies instead.
   */
  targetsAlly?: boolean;
  /** Phase 13.7 (D-092): HP restored to the target, for a `targetsAlly` healing spell. */
  healAmount?: number;
  /** Phase 16 (D-106): for `kind: "aoeAtRange"`, the blast radius around the CHOSEN tile (as opposed to `rangeTiles`, how far away that tile may be). */
  radiusTiles?: number;
  /**
   * Phase 16 (D-106): a `targetsAlly` spell with this set applies to EVERY
   * living ally at once (heal and/or buff), no aiming needed — the stand-in
   * for a multi-target spell like Mass Healing Word or a party-wide Bless,
   * simplified from "choose up to N targets" to "the whole party," since
   * this game's roster is already small (up to four heroes).
   */
  areaAllies?: boolean;
  /** Phase 16 (D-106): a lingering ally buff (see data/buffEffects.ts) this spell grants its target(s) — combinable with `healAmount` on the same spell, or usable alone. */
  appliesBuff?: { buffId: BuffEffectId; durationTurns: number };
  /**
   * Phase 16 (D-106): on a landed hit, pushes the enemy target directly away
   * from the caster this many tiles (stopping early if blocked) — the
   * stand-in for every SRD forced-movement spell (Thunderwave, Gust of
   * Wind's shove, etc.).
   */
  forcedMoveTiles?: number;
  /**
   * Phase 16 (D-106): this spell teleports the CASTER to an empty tile the
   * player chooses, up to `rangeTiles` away — the stand-in for every SRD
   * short-range self-teleport spell (Misty Step, Dimension Door, etc.).
   * Mutually exclusive with every enemy/ally-targeting field above.
   */
  teleportSelf?: boolean;
  /**
   * Phase 16 (D-106): this spell summons a temporary ally at an empty tile
   * the player chooses, up to `rangeTiles` away — see `data/summons.ts` for
   * the summon's own stat block and `SummonSystem` for its lifecycle.
   */
  summonsId?: string;
  /** Phase 16 (D-106): how many hero turns the summon lasts, for a `summonsId` spell. */
  summonDurationTurns?: number;
  /**
   * Phase 16 (D-106): this spell places a temporary structure (see
   * data/structures.ts) at an empty tile the player chooses, up to
   * `rangeTiles` away — the stand-in for every SRD terrain-shaping spell
   * (Wall of Stone, Web, Spike Growth, etc.). Reuses `BuildSystem.place`,
   * the same validation a built wall already gets (never sealing off every
   * spawn-to-exit route).
   */
  altersTerrainId?: string;
  /** Phase 16 (D-106): how many hero turns the placed structure lasts, for an `altersTerrainId` spell. */
  terrainDurationTurns?: number;
  /**
   * D-131: this ability's real SRD damage type, set ONLY for a real
   * castable spell (an id referenced by some `spells.ts` entry's
   * `abilityId`) whose canonical 5e version deals damage of a specific
   * type. Left ABSENT for the four original non-spell Phase-4 abilities
   * (`cleave`/`piercing-shot`/`taunting-slam`/`frost-bolt` — not SRD
   * content) and for any spell whose nonzero `damage` here is this
   * project's own stand-in for a real 5e spell that deals NO damage at all
   * (a control/debuff/buff/heal/summon/terrain/teleport spell given a small
   * hit-number or duration to fit this game's single-target-attack/ally
   * engine — e.g. `command`, `charm-person`, `sleep`, `bane`) — inventing a
   * type for those would fabricate SRD content this project's own "verify,
   * don't assume" convention (see spells.ts) explicitly avoids. See
   * `CombatSystem.applyResistance` for how this interacts with an enemy's
   * `damageResistances`/`damageVulnerabilities`/`damageImmunities`.
   */
  damageType?: DamageType;
  /**
   * D-137: set ONLY for a spell whose real SRD version genuinely deals TWO
   * (or more) damage types in the same instance of damage — e.g. Meteor
   * Swarm (fire+bludgeoning, even split) or Ice Storm (bludgeoning+cold,
   * uneven split per its actual dice: 2d8 vs. 4d6). Each entry's `portion`
   * is the fraction of `damage` that type deals; the portions must sum to 1.
   * `damageType` above should still be set to the split's "primary"/
   * name-matching type when this is present — see `AttackProfile.damageTypes`
   * in `CombatSystem` for why (VisualFxSystem's color/death-cause lookup
   * only ever reads the singular `damageType`, not this array) and for how
   * the resistance math actually uses this field instead once it's present.
   * Left absent for every spell that deals only one real type, and for
   * `storm-of-vengeance` (D-131) — its SRD mix is different types on
   * DIFFERENT ROUNDS of a multi-round effect, not two types on the SAME hit,
   * so it doesn't fit this "split one instance of damage" shape.
   */
  damageTypes?: ReadonlyArray<DamageTypeSplit>;
}

