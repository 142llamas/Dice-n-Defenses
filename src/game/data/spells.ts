/** Look up a spell, throwing on an unknown id so typos fail loudly. */
export function getSpell(id: string): SpellDefinition {
  const def = SPELLS[id];
  if (!def) throw new Error(`Unknown spell id "${id}".`);
  return def;
}

/** True if `id` names a spell in the curated list above (cantrip or leveled). */
export function isSpellId(id: string): boolean {
  return id in SPELLS;
}

/** Every curated spell at exactly this SRD spell level (0 = cantrips). */
export function spellsAtLevel(level: number): SpellDefinition[] {
  return Object.values(SPELLS).filter((s) => s.level === level);
}

/** Cantrips that are mechanically playable today — i.e. carry a real `abilityId`. */
export function mechanicallyActiveCantrips(): SpellDefinition[] {
  return spellsAtLevel(0).filter((s) => s.abilityId !== undefined);
}

/** The combat-numbers `AbilityDefinition` a mechanically-active spell casts as. */
export function abilityForSpell(spell: SpellDefinition): AbilityDefinition {
  if (!spell.abilityId) {
    throw new Error(`Spell "${spell.id}" has no abilityId — it isn't castable in a battle yet.`);
  }
  return getAbility(spell.abilityId);
}
