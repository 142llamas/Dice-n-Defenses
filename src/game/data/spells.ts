/**
 * Spell list — Phase 11.2's spellcasting engine (DECISIONS D-071/D-074),
 * extended in Phase 11.3 (D-075) for the Cleric, in Phase 13.8 (D-093) for
 * four more casters, and in Phase 15 (D-104) into a FULL SRD spell catalogue.
 *
 * SRD-derived content (see CONTENT_SOURCES.md): the spell NAMES, their
 * spell level (0 = cantrip, 1-9 leveled), and school are SRD-derived. The
 * original 14 curated spells (through Phase 13.8) follow SRD 5.2.1 under
 * CC BY 4.0. Phase 15's ~300-entry addition below follows **SRD 5.1**
 * instead (usable under CC BY 4.0 or OGL 1.0a) — verified directly against
 * two independent SRD 5.1 mirrors (cross-checked against each other and
 * against a third-party open-data spell API for school assignment) rather
 * than assumed, per this file's own "verify, don't assume" rule (D-098/
 * D-099). All DESCRIPTIONS and game NUMBERS below are original to this
 * project, not copied SRD text — same treatment as the Fighter class table
 * in `data/classes.ts`.
 *
 * A spell is one of two kinds, matching the class-table precedent's
 * `mechanicallyActive` flag on `ClassFeature`:
 * - **Cantrips** (`level: 0`) are cast at-will, no slot cost — this game's
 *   move-plus-one-action turn already supports that, so every cantrip here
 *   has an `abilityId` pointing at a real, playable entry in
 *   `data/abilities.ts` (the actual combat numbers live there, not
 *   duplicated here).
 * - **Leveled spells** (`level >= 1`) require spending a spell slot.
 *   Phase 13.7 (D-092) built the real slot economy (`Hero.spellSlotsRemaining`,
 *   spent via `BattleScene`'s spellbook), so a leveled spell now CAN carry an
 *   `abilityId` — Magic Missile (Wizard) and Cure Wounds (Cleric) are the
 *   first two. Every other leveled spell here still has none: this game has
 *   no ally-buff mechanic (Bless, Shield of Faith) or skill-check system
 *   (Guidance) to hook them into yet, a separate boundary from the slot
 *   economy itself.
 *
 * Phase 15 (D-104): every spell added this phase is DATA-ONLY (no
 * `abilityId`, no change to `characterCreation.ts`'s known-spell-lists) —
 * this phase is a catalogue/logging pass ("add as many SRD spells as
 * possible"), not a new-mechanics pass. Most of these ~300 spells describe
 * effects this game has no system for yet (AoE at range beyond adjacency,
 * ally buffs, summons, terrain/illusion/utility effects, multi-target heals
 * beyond the two already wired) — same honest "inert until a system exists"
 * treatment already given to Bless/Burning Hands/Mage Armor/Guidance/
 * Shield of Faith above. A future session can pick specific ones to wire up
 * on request, the same way Fire Bolt/Magic Missile/Cure Wounds were.
 */

